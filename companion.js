  find('buddy-question').value=String(memo.question||'').slice(0,600);
  const save=()=>{
    const next={...store.get(),notes:find('buddy-notes').value,question:find('buddy-question').value};
    const ok=store.put(next);
    find('notes-status').textContent=ok?'Saved on this device ✓':'Storage unavailable. Export your notes instead.';
    return ok;
  };
  let timer;
  find('buddy-notes').addEventListener('input',()=>{clearTimeout(timer);find('notes-status').textContent='Saving…';timer=setTimeout(save,550)});
  find('buddy-question').addEventListener('input',()=>{clearTimeout(timer);timer=setTimeout(save,600)});
