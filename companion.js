const common = new Set('a an the of to and or what which is are in for from on with how why explain give me about this that does do use used between can be one best type example identify following correct answer question please'.split(' '));
const words = (s) => (String(s||'').toLowerCase().match(/[a-z0-9]+/g)||[]).filter(x => x.length > 2 && !common.has(x));
function matches(query, text) {
  const w = words(query), t = new Set(words(text));
  if (!w.length) return 0;
  const hits = w.filter(x=>t.has(x)).length;
  return hits / Math.sqrt(w.length * Math.max(4,t.size));
}
function topicResults(query) {
  const found=[];
  for(const c of catalog){
    for(const [nid,q,answer,,why] of bankFor(c.id)||[]){
      const score=matches(query,q);
      if(score>.065) found.push({score,type:'question',course:c,name:c.name,nid,question:splitQuestion(q).prompt,answer,why:why||''});
    }
    for(const note of window.SUBJECT_DATA?.[c.id]?.notes||[]){
      const text=(note.html||'').replace(/<[^>]+>/g,' ').replace(/&[a-z]+;/g,' ');
      const score=matches(query,note.title+' '+(note.sum||'')+' '+text.slice(0,1400));
      if(score>.05) found.push({score:score*.77,type:'lesson',course:c,name:c.name,nid:note.id,question:note.title,answer:note.sum||text.slice(0,270),why:''});
    }
  }
  return found.sort((a,b)=>b.score-a.score).slice(0,4);
}
function readStore(uid) {
  const k='br_companion_'+uid;
  return {
    get(){try {return JSON.parse(localStorage.getItem(k)||'{}')}catch{return {}}},
    put(data){try{localStorage.setItem(k,JSON.stringify(data));return true}catch{return false}}
  };
}
